/// The social apps this plugin can share to and detect.
enum SocialApp {
  /// WhatsApp Messenger.
  whatsapp,

  /// Telegram.
  telegram,

  /// Instagram (feed, story, reels, and direct messages).
  instagram,

  /// The Facebook app.
  facebook,

  /// Facebook Messenger.
  messenger,

  /// TikTok (Android only).
  tiktok,

  /// X (formerly Twitter).
  x,

  /// The device's SMS app.
  sms,
}
